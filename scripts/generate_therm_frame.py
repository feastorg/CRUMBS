"""Write docs/figures/src/therm-frame.tex from tests/golden_vectors/vectors.json.

The figure is docs/create-a-family.md's worked frame: therm_send_alarm() for
channel 1 and a limit of 3000. Its bytes are the encode vector with type_id
0x07 and opcode 0x02, which gen_vectors.c builds with therm_alarm_pack(), so
the figure shows what the core sends. CI reruns this script and fails if the
committed .tex differs; then build_figures.sh turns it into the SVG.

    python3 scripts/generate_therm_frame.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VECTORS = ROOT / "tests" / "golden_vectors" / "vectors.json"
OUT = ROOT / "docs" / "figures" / "src" / "therm-frame.tex"

TYPE_ID, OPCODE = 0x07, 0x02  # THERM_TYPE_ID, THERM_OP_SET_ALARM


def main() -> None:
    cases = [
        c
        for c in json.loads(VECTORS.read_text())["encode"]
        if c["type_id"] == TYPE_ID and c["opcode"] == OPCODE
    ]
    if len(cases) != 1:
        raise SystemExit(f"expected one therm alarm vector in {VECTORS}, found {len(cases)}")
    frame = bytes.fromhex(cases[0]["frame"])
    data = bytes.fromhex(cases[0]["data"])
    if len(data) != 3 or frame[2] != len(data) or len(frame) != 4 + len(data):
        raise SystemExit(f"the therm alarm vector is not a 3-byte payload: {cases[0]}")

    ch = data[0]
    limit = int.from_bytes(data[1:3], "little", signed=True)
    cells = [f"0x{b:02X}" for b in frame]
    OUT.write_text(
        TEMPLATE.format(
            b0=cells[0],
            b1=cells[1],
            b2=cells[2],
            b3=cells[3],
            b4=cells[4],
            b5=cells[5],
            b6=cells[6],
            n=len(data),
            f=len(frame),
            nc=len(frame) - 1,
            ch=ch,
            limit=limit,
            hi=data[2],
            lo=data[1],
            deg=f"{limit / 100:.2f}".replace("-", "$-$"),
        )
    )
    print(f"generate_therm_frame: {OUT.relative_to(ROOT)}")


TEMPLATE = r"""% Generated by scripts/generate_therm_frame.py from
% tests/golden_vectors/vectors.json. Do not edit; rerun the script.
% The worked therm frame (docs/create-a-family.md).
\documentclass[border=6pt]{{standalone}}
\usepackage{{crumbs-fig}}
\begin{{document}}
\begin{{tikzpicture}}
  \def\w{{1.8}}

  \node[note, anchor=south west, align=left] at (0, 1.6)
    {{\texttt{{therm\_send\_alarm(dev, \&v)}} with \texttt{{v.ch = {ch}}},
      \texttt{{v.limit = {limit}}} puts these {f} bytes on the bus:}};

  % row labels, left of the frame
  \node[note, anchor=south east] at (-0.15, 0.95) {{byte offset}};
  \node[note, anchor=east]       at (-0.15, 0.45) {{byte}};
  \node[note, anchor=north east] at (-0.15, -0.05) {{field}};
  \node[note, anchor=north east] at (-0.15, -0.6) {{meaning}};

  % the bytes
  \foreach \i/\b/\c in {{0/{b0}/crumbsHeader, 1/{b1}/crumbsHeader, 2/{b2}/crumbsHeader,
                       3/{b3}/crumbsData, 4/{b4}/crumbsData, 5/{b5}/crumbsData,
                       6/{b6}/crumbsCrc}} {{
    \node[field, fill=\c, minimum width=\w cm, anchor=south west] at (\i*\w, 0) {{\b}};
    \node[note, font=\ttfamily\scriptsize, anchor=south] at (\i*\w+0.5*\w, 0.95) {{\i}};
  }}

  % field names
  \foreach \i/\t in {{0/type\_id, 1/opcode, 2/data\_len, 3/ch, 6/crc8}}
    \node[note, font=\ttfamily\footnotesize, anchor=north] at (\i*\w+0.5*\w, -0.05) {{\t}};
  \node[note, font=\ttfamily\footnotesize, anchor=north] at (5*\w, -0.05)
    {{limit (i16)}};

  % meanings
  \node[note, anchor=north, text width=\w cm] at (0.5*\w, -0.6) {{\texttt{{THERM\_\\TYPE\_ID}}}};
  \node[note, anchor=north, text width=\w cm] at (1.5*\w, -0.6)
    {{\texttt{{THERM\_OP\_\\SET\_ALARM}}}};
  \node[note, anchor=north, text width=\w cm] at (2.5*\w, -0.6) {{{n} data\\bytes follow}};
  \node[note, anchor=north, text width=\w cm] at (3.5*\w, -0.6) {{channel {ch}}};
  \node[note, anchor=north, text width=2*\w cm] at (5*\w, -0.6)
    {{low byte first:\\\texttt{{0x{hi:02X}{lo:02X}}} = {limit}, so {deg}\,\textdegree C}};
  \node[note, anchor=north, text width=\w cm] at (6.5*\w, -0.6) {{check byte}};

  % coverage
  \draw[brace, decoration={{mirror}}] (0,-1.6) -- (6*\w,-1.6)
    node[midway, below=6pt, note]
    {{the CRC-8/SMBUS of these {nc} bytes is \texttt{{{b6}}}, the last byte}};
\end{{tikzpicture}}
\end{{document}}
"""

if __name__ == "__main__":
    main()
